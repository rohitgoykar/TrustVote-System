def clean_name(name):
    if not name:
        return ""
    # Strip Marathi notes or brackets e.g. "कर्जत पंचायत समिती (Karjat)" -> "Karjat"
    for part in name.replace("पंचायत समिती", "").replace("तालुका", "").replace("(", " ").replace(")", " ").split():
        for key in TALUKA_GRAM_PANCHAYATS_DB.keys():
            if key.lower() == part.lower() or part.lower() in key.lower():
                return key
    return name.strip()

def get_grampanchayats_by_taluka(taluka_input, district_input=None):
    """
    AI / Smart retrieval of all Gram Panchayats under a specific Taluka.
    """
    cleaned_taluka = clean_name(taluka_input)
    
    # 1. Exact match in database
    if cleaned_taluka in TALUKA_GRAM_PANCHAYATS_DB:
        gps = TALUKA_GRAM_PANCHAYATS_DB[cleaned_taluka]
        return {
            "status": "success",
            "taluka": cleaned_taluka,
            "district": district_input or "Maharashtra",
            "source": "AI-Verified Maharashtra Electoral Roll",
            "count": len(gps),
            "gram_panchayats": gps
        }
    
